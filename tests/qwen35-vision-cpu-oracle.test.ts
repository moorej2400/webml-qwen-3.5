test("decodes BF16 and evaluates a two-slice Conv3D patch projection before one bias", () => {
  close(Array.from(decodeBfloat16(new Uint16Array([0x3f80, 0xc020, 0x7fc0]))), [1, -2.5, Number.NaN], 0);
  close(Array.from(visionTemporalConv3dPatchEmbed({
    temporalSlices: [new Float32Array([1, 2]), new Float32Array([3, 4])],
    temporalWeights: [
      new Float32Array([1, 10, 2, 20]),
      new Float32Array([3, 30, 4, 40]),
    ],
    bias: new Float32Array([100, 200]),
    inputChannels: 1,
    patchHeight: 1,
    patchWidth: 2,
    outputWidth: 2,
  })), [250, 414]);

  assert.throws(() => visionTemporalConv3dPatchEmbed({
    temporalSlices: [new Float32Array(2), new Float32Array(2)],
    temporalWeights: [new Float32Array(4), new Float32Array(4)],
    bias: new Float32Array(2),
    inputChannels: 1,
    patchHeight: 2,
    patchWidth: 2,
    outputWidth: 2,
  }), /Conv3D.*shape/i);
});

test("stays within the pinned PyTorch envelope at the production hidden width", () => {
  const inputWidth = 1_024;
  const outputWidth = 8;
  const values = Float32Array.from(
    { length: inputWidth },
    (_, index) => Math.fround(Math.sin(index * 0.13) * 3),
  );
  const weight = Uint16Array.from(
    { length: inputWidth * outputWidth },
    (_, index) => 0x3c00 + ((index * 37) % 0x600),
  );
  const actual = visionLinearBf16({
    input: values,
    tokenCount: 1,
    inputWidth,
    outputWidth,
    weight,
    bias: Float32Array.from({ length: outputWidth }, (_, index) => Math.fround(index * 0.1)),
  });

  // Generated by PyTorch 2.8.0 CPU F.linear from the deterministic inputs above.
  closePyTorch(Array.from(actual), [
    -722.221923828125,
    62.914031982421875,
    929.163818359375,
    -721.9219360351562,
    63.214019775390625,
    929.4637451171875,
    -721.6219482421875,
    63.5140380859375,
  ]);
});

