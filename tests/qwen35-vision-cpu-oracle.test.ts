function close(actual: readonly number[], expected: readonly number[], tolerance = 1e-6): void {
  assert.equal(actual.length, expected.length);
  for (let index = 0; index < expected.length; index += 1) {
    if (Number.isNaN(expected[index]!)) {
      assert.ok(Number.isNaN(actual[index]!));
      continue;
    }
    assert.ok(Math.abs(actual[index]! - expected[index]!) <= tolerance, `value ${index}: ${actual[index]} !== ${expected[index]}`);
  }
}

function closePyTorch(actual: readonly number[], expected: readonly number[]): void {
  const { absoluteTolerance, relativeTolerance } =
    QWEN35_VISION_CPU_ORACLE_REFERENCE.pytorchFixtureTolerance;
  assert.equal(actual.length, expected.length);
  for (let index = 0; index < expected.length; index += 1) {
    const allowed = absoluteTolerance + relativeTolerance * Math.abs(expected[index]!);
    assert.ok(
      Math.abs(actual[index]! - expected[index]!) <= allowed,
      `value ${index}: ${actual[index]} !== ${expected[index]}`,
    );
  }
}

